"""Regenerate the 240 offline parity cases: python -B demo/make_fixtures.py."""
import json
import sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from advisor.core import advise
from advisor.features import featurize
from advisor.policy import choose
from advisor.config import DEFAULTS
from advisor.clusters import projection

PROMPTS = [
 'Say hello.', 'Write a friendly thank-you note.', 'Summarize this paragraph: Bees pollinate flowers.',
 'Translate good morning into French.', 'Rewrite this sentence clearly: The meeting was held.',
 'Calculate 17 + 25.', 'Solve the equation 2*x + 4 = 10.', 'What is the probability of two heads?',
 'Multiply 1.5 by 8 and sum 2 and 3.', 'Return exactly one JSON object with a name field.',
 'Write a Python function to sort records.', 'Debug this JavaScript API bug and add tests.',
 'Refactor a TypeScript class in a repository.', 'Design SQL indexes for a production database.',
 'Explain this code: ```python\nprint(1)\n```', 'Find the latest weather and cite a source.',
 'Search current documentation for the API.', 'Look up news today.', 'Compare the price on this website.',
 'Draft a legal contract.', 'Explain medical patient safety critical checks.', 'Give financial advice on tax.',
 'Improve this somehow and make it good.', 'What is the best way to do something?',
 'First list options, then compare them, finally recommend one.', 'Plan meals and shops and travel and cleanup.',
 '1. Read notes\n2. Write a summary\n3. Check it', '- Gather numbers\n- Calculate totals',
 'Make a table of 3, 5, 7, 11 and 13.', 'Read src/main.py and config.json at https://example.org/docs.',
 'Please create only a JSON table; it must have exactly 4 rows.', 'That is wrong; try again instead.',
 'Explain gravity to a child?', 'Write about café, naïve art and 東京.', '你好，解释这个概念。',
 'Compare 🐈 and 🐕 in one sentence.', 'Tell a story. ' * 190,
 'Review the following text:\n' + 'a' * 1450, 'Explain `x` and `y` in plain language.',
 'Outline a research plan for ocean ecosystems.'
]

def main():
    root=Path(__file__).parent
    cases=[]
    for text in PROMPTS:
        for stakes in ('low','medium','high'):
            a=advise(text,stakes,persist=False); a.pop('advice_id')
            f=featurize(text,stakes,fast=True)
            for engine in ('claude','codex'):
                pick=choose(f,engine,exploration=0,weights={},baseline={},rows=[],objective='threshold',cfg=DEFAULTS)
                cases.append(dict(text=text,stakes=stakes,engine=engine,core=a,features=f,recommendation={k:pick[k] for k in ('id','effort','predicted','why')}))
    (root/'fixtures.json').write_text(json.dumps(cases,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (root/'projection.js').write_text('// Python random.Random(61119) projection; generated by make_fixtures.py.\nexport const projection='+json.dumps(projection(),separators=(',',':'))+';\n',encoding='utf-8')
    print(f'Generated {len(cases)} cases (40 prompts × 3 stakes × 2 engines).')

if __name__=='__main__': main()
